CREATE OR REPLACE VIEW V_RECEP_HABITACIONES AS
SELECT h.ID_HABITACION,h.ID_ALOJAMIENTO,h.NUMERO,h.CAPACIDAD,h.TIPO,h.ACTIVA
FROM HABITACION h WHERE EXISTS(SELECT 1 FROM SEG_USUARIO_ALOJAMIENTO s
 WHERE s.USUARIO_ORACLE=SYS_CONTEXT('USERENV','SESSION_USER') AND s.ID_ALOJAMIENTO=h.ID_ALOJAMIENTO);
CREATE OR REPLACE VIEW V_RECEP_RESERVAS AS
SELECT r.ID_RESERVA,r.FECHA_CHECKIN,r.FECHA_CHECKOUT,r.ESTADO
FROM RESERVA r WHERE EXISTS(SELECT 1 FROM RESERVA_HABITACION d JOIN HABITACION h ON h.ID_HABITACION=d.ID_HABITACION
 JOIN SEG_USUARIO_ALOJAMIENTO s ON s.ID_ALOJAMIENTO=h.ID_ALOJAMIENTO
 WHERE d.ID_RESERVA=r.ID_RESERVA AND s.USUARIO_ORACLE=SYS_CONTEXT('USERENV','SESSION_USER'));
CREATE OR REPLACE VIEW V_ADMIN_RESERVAS AS
SELECT r.ID_RESERVA,r.FECHA_CHECKIN,r.FECHA_CHECKOUT,r.ESTADO
FROM RESERVA r WHERE EXISTS(SELECT 1 FROM RESERVA_HABITACION d JOIN HABITACION h ON h.ID_HABITACION=d.ID_HABITACION
 JOIN SEG_USUARIO_ALOJAMIENTO s ON s.ID_ALOJAMIENTO=h.ID_ALOJAMIENTO
 WHERE d.ID_RESERVA=r.ID_RESERVA AND s.USUARIO_ORACLE=SYS_CONTEXT('USERENV','SESSION_USER'))
WITH CHECK OPTION;
CREATE OR REPLACE VIEW V_ADMIN_HABITACIONES AS
SELECT h.ID_HABITACION,h.ID_ALOJAMIENTO,h.NUMERO,h.CAPACIDAD,h.TIPO,h.DESCRIPCION,h.ACTIVA
FROM HABITACION h WHERE EXISTS(SELECT 1 FROM SEG_USUARIO_ALOJAMIENTO s
 WHERE s.USUARIO_ORACLE=SYS_CONTEXT('USERENV','SESSION_USER') AND s.ID_ALOJAMIENTO=h.ID_ALOJAMIENTO)
WITH CHECK OPTION;
CREATE OR REPLACE VIEW V_ADMIN_TARIFAS AS
SELECT t.ID_TARIFA,t.ID_HABITACION,t.ID_TEMPORADA,t.PRECIO_NOCHE FROM TARIFA t
WHERE EXISTS(SELECT 1 FROM HABITACION h JOIN SEG_USUARIO_ALOJAMIENTO s ON s.ID_ALOJAMIENTO=h.ID_ALOJAMIENTO
 WHERE h.ID_HABITACION=t.ID_HABITACION AND s.USUARIO_ORACLE=SYS_CONTEXT('USERENV','SESSION_USER'))
WITH CHECK OPTION;
CREATE OR REPLACE VIEW V_GERENCIA_INGRESOS AS
SELECT h.ID_ALOJAMIENTO,TRUNC(p.FECHA_PAGO,'MM') MES,
 SUM(p.MONTO-p.MONTO_REEMBOLSADO) RECAUDO_NETO
FROM PAGO p JOIN (SELECT DISTINCT d.ID_RESERVA,h.ID_ALOJAMIENTO FROM RESERVA_HABITACION d
 JOIN HABITACION h ON h.ID_HABITACION=d.ID_HABITACION) h ON h.ID_RESERVA=p.ID_RESERVA
WHERE p.ESTADO IN ('EXITOSO','REEMBOLSADO') GROUP BY h.ID_ALOJAMIENTO,TRUNC(p.FECHA_PAGO,'MM');
CREATE OR REPLACE VIEW V_GERENCIA_OCUPACION AS SELECT * FROM MV_OCUPACION_MENSUAL;
CREATE OR REPLACE VIEW V_AUDITOR_TARIFAS AS SELECT * FROM AUDITORIA_TARIFA;
CREATE OR REPLACE VIEW V_AUDITOR_PAGOS AS
SELECT ID_PAGO,ID_RESERVA,FECHA_PAGO,MONTO,MONTO_REEMBOLSADO,METODO,ESTADO FROM PAGO;
