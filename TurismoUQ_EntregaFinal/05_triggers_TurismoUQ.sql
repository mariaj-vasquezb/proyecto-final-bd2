-- Disparador de FILA exigido: sincroniza el espejo y rechaza solapes.
CREATE OR REPLACE TRIGGER TRG_EVITAR_SOLAPAMIENTO
BEFORE INSERT OR UPDATE OR DELETE ON RESERVA_HABITACION FOR EACH ROW
DECLARE
  v_estado RESERVA.ESTADO%TYPE;
  v_habitacion NUMBER;
  v_n NUMBER;
  v_excluir NUMBER := -1;
BEGIN
  IF DELETING THEN
    DELETE FROM CONTROL_OCUPACION_RH WHERE ID_RESERVA_HAB=:OLD.ID_RESERVA_HAB;
  ELSE
    SELECT ID_HABITACION INTO v_habitacion FROM HABITACION
      WHERE ID_HABITACION=:NEW.ID_HABITACION FOR UPDATE;
    SELECT ESTADO INTO v_estado FROM RESERVA WHERE ID_RESERVA=:NEW.ID_RESERVA;
    IF UPDATING THEN v_excluir:=:OLD.ID_RESERVA_HAB; END IF;
    IF :NEW.FECHA_CHECKOUT<=:NEW.FECHA_CHECKIN THEN
      RAISE_APPLICATION_ERROR(-20025,'CHECKOUT debe ser posterior a CHECKIN');
    END IF;
    IF v_estado IN ('CONFIRMADA','COMPLETADA') THEN
      SELECT COUNT(*) INTO v_n FROM CONTROL_OCUPACION_RH c
      JOIN RESERVA r ON r.ID_RESERVA=c.ID_RESERVA
      WHERE c.ID_HABITACION=:NEW.ID_HABITACION AND c.ID_RESERVA_HAB<>v_excluir
        AND c.FECHA_CHECKIN<:NEW.FECHA_CHECKOUT AND c.FECHA_CHECKOUT>:NEW.FECHA_CHECKIN
        AND r.ESTADO IN ('CONFIRMADA','COMPLETADA');
      IF v_n>0 THEN RAISE_APPLICATION_ERROR(-20026,'Habitacion ocupada: reserva confirmada solapada'); END IF;
    END IF;
    IF INSERTING THEN
      INSERT INTO CONTROL_OCUPACION_RH VALUES
        (:NEW.ID_RESERVA_HAB,:NEW.ID_RESERVA,:NEW.ID_HABITACION,:NEW.FECHA_CHECKIN,:NEW.FECHA_CHECKOUT);
    ELSE
      UPDATE CONTROL_OCUPACION_RH SET ID_RESERVA_HAB=:NEW.ID_RESERVA_HAB,
        ID_RESERVA=:NEW.ID_RESERVA,ID_HABITACION=:NEW.ID_HABITACION,
        FECHA_CHECKIN=:NEW.FECHA_CHECKIN,FECHA_CHECKOUT=:NEW.FECHA_CHECKOUT
      WHERE ID_RESERVA_HAB=:OLD.ID_RESERVA_HAB;
      IF SQL%ROWCOUNT<>1 THEN RAISE_APPLICATION_ERROR(-20027,'Asignacion no encontrada en tabla auxiliar'); END IF;
    END IF;
  END IF;
END TRG_EVITAR_SOLAPAMIENTO;
/

CREATE OR REPLACE TRIGGER TRG_VALIDAR_RH
FOR INSERT OR UPDATE OR DELETE ON RESERVA_HABITACION COMPOUND TRIGGER
