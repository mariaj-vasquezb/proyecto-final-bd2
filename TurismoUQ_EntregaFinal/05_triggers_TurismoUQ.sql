  BEGIN
    IF NOT INSERTING THEN g_ids(:OLD.ID_RESERVA):=TRUE; END IF;
    IF NOT DELETING THEN g_ids(:NEW.ID_RESERVA):=TRUE; END IF;
  END AFTER EACH ROW;
  AFTER STATEMENT IS
    v_id PLS_INTEGER;
  BEGIN
    v_id:=g_ids.FIRST;
    WHILE v_id IS NOT NULL LOOP
      PKG_REGLAS_TURISMOUQ.VALIDAR_RESERVA(v_id); v_id:=g_ids.NEXT(v_id);
    END LOOP;
  END AFTER STATEMENT;
END TRG_VALIDAR_RH;
