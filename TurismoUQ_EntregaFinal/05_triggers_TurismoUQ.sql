-- DBEAVER + ORACLE XE 21c.
-- Para SQL: ejecutar una sentencia. Para PL/SQL: seleccionar el bloque completo
-- DECLARE/BEGIN o CREATE...END; sin la linea / y usar Ejecutar sentencia SQL.
-- Conservar la misma conexion para SAVEPOINT/ROLLBACK. Activar salida DBMS Output.
-- TURISMOUQ | ENTREGA 2 | DISPARADORES Y REGLAS COMPLEMENTARIAS
-- Oracle XE 21c. Instalacion limpia, despues de 01, 02 y 04.
-- En DBeaver usar modo script con delimitador PL/SQL '/' en linea independiente.
-- Se mantiene auditoria principal AFTER STATEMENT y solape BEFORE EACH ROW.
-- Los triggers compuestos auxiliares validan al terminar la sentencia y evitan
-- consultar tablas mutantes. No confundirlos con los dos triggers de la rubrica.
-- Las escrituras relacionadas toman primero CONTROL_INTEGRIDAD(1). Es una
-- serializacion conservadora para este proyecto; limita el paralelismo entre
-- alojamientos. El bloqueo dura hasta COMMIT/ROLLBACK, no solo hasta el trigger.

CREATE TABLE AUDITORIA_TARIFA (
    ID_AUDITORIA NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_TARIFA NUMBER NOT NULL,
    PRECIO_ANTERIOR NUMBER (12, 2) NOT NULL,
    PRECIO_NUEVO NUMBER (12, 2) NOT NULL,
    USUARIO_CAMBIO VARCHAR2 (128) NOT NULL,
    FECHA_CAMBIO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_AUDITORIA_TARIFA PRIMARY KEY (ID_AUDITORIA)
);

CREATE GLOBAL TEMPORARY
TABLE TMP_CAMBIOS_TARIFA (
    ID_TARIFA NUMBER NOT NULL,
    PRECIO_ANTERIOR NUMBER (12, 2) NOT NULL,
    PRECIO_NUEVO NUMBER (12, 2) NOT NULL
) ON
COMMIT DELETE ROWS;

CREATE OR REPLACE TRIGGER TRG_CAPTURAR_CAMBIOS_TARIFA
AFTER UPDATE OF PRECIO_NOCHE
ON TARIFA
FOR EACH ROW
BEGIN
    IF :OLD.PRECIO_NOCHE <> :NEW.PRECIO_NOCHE
       OR (:OLD.PRECIO_NOCHE IS NULL AND :NEW.PRECIO_NOCHE IS NOT NULL)
       OR (:OLD.PRECIO_NOCHE IS NOT NULL AND :NEW.PRECIO_NOCHE IS NULL)
    THEN
        INSERT INTO TMP_CAMBIOS_TARIFA (
            ID_TARIFA,
            PRECIO_ANTERIOR,
            PRECIO_NUEVO
        )
        VALUES (
            :NEW.ID_TARIFA,
            :OLD.PRECIO_NOCHE,
            :NEW.PRECIO_NOCHE
        );
    END IF;
END TRG_CAPTURAR_CAMBIOS_TARIFA;
/


CREATE OR REPLACE TRIGGER TRG_AUDITORIA_TARIFA
AFTER UPDATE OF PRECIO_NOCHE
ON TARIFA
BEGIN
    FOR r IN (
        SELECT ID_TARIFA, PRECIO_ANTERIOR, PRECIO_NUEVO
        FROM TMP_CAMBIOS_TARIFA
    ) LOOP
        INSERT INTO AUDITORIA_TARIFA (
            ID_TARIFA,
            PRECIO_ANTERIOR,
            PRECIO_NUEVO,
            USUARIO_CAMBIO,
            FECHA_CAMBIO
        )
        VALUES (
            r.ID_TARIFA,
            r.PRECIO_ANTERIOR,
            r.PRECIO_NUEVO,
            SYS_CONTEXT('USERENV', 'SESSION_USER'),
            SYSTIMESTAMP
        );
    END LOOP;

    DELETE FROM TMP_CAMBIOS_TARIFA;
END TRG_AUDITORIA_TARIFA;
/


SELECT
    TRIGGER_NAME,
    TRIGGER_TYPE,
    TABLE_NAME,
    STATUS
FROM USER_TRIGGERS
WHERE
    TRIGGER_NAME IN (
        'TRG_CAPTURAR_CAMBIOS_TARIFA',
        'TRG_AUDITORIA_TARIFA'
