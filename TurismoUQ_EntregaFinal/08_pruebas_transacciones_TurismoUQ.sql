-- Para SQL: ejecutar una sentencia. Para PL/SQL: seleccionar el bloque completo
-- DECLARE/BEGIN o CREATE...END; sin la linea / y usar Ejecutar sentencia SQL.
-- Conservar la misma conexion para SAVEPOINT/ROLLBACK. Activar salida DBMS Output.
-- Sesion dedicada TURISMOUQ, AUTOCOMMIT OFF, DBMS Output ON.
SAVEPOINT e3_inicio;
DELETE FROM E3_DEMO_TX;
INSERT INTO E3_DEMO_TX(ETIQUETA) VALUES('ANTERIOR_AL_SAVEPOINT');
DECLARE
 v_h NUMBER; v_r NUMBER; v_p NUMBER;
BEGIN
 SELECT h.ID_HABITACION INTO v_h FROM HABITACION h WHERE h.ACTIVA='S' AND NOT EXISTS(
  SELECT 1 FROM RESERVA_HABITACION d JOIN RESERVA r ON r.ID_RESERVA=d.ID_RESERVA
  WHERE d.ID_HABITACION=h.ID_HABITACION AND r.ESTADO IN ('CONFIRMADA','COMPLETADA')
  AND d.FECHA_CHECKIN<DATE '2026-12-12' AND d.FECHA_CHECKOUT>DATE '2026-12-10')
 ORDER BY h.ID_HABITACION FETCH FIRST 1 ROW ONLY;
 SP_RESERVA_PAGO_ATOMICA(1,v_h,DATE '2026-12-10',DATE '2026-12-12',1,100000,'PSE',v_r,v_p);
 INSERT INTO E3_DEMO_TX VALUES('RESERVA_Y_PAGO_PREVIA',v_r,v_p);
 DBMS_OUTPUT.PUT_LINE('Creacion atomica correcta: reserva='||v_r||'; pago='||v_p);
END;
/
-- FIGURA 3.1
SELECT r.ID_RESERVA,r.ESTADO,p.ID_PAGO,p.MONTO,p.ESTADO ESTADO_PAGO
FROM E3_DEMO_TX d JOIN RESERVA r ON r.ID_RESERVA=d.ID_RESERVA JOIN PAGO p ON p.ID_PAGO=d.ID_PAGO;
-- FIGURA 3.2: la primera reserva y su pago son ANTERIORES al punto.
SAVEPOINT e3_parcial;
SELECT ETIQUETA,'SAVEPOINT E3_PARCIAL establecido' PUNTO FROM E3_DEMO_TX;
DECLARE
 v_h NUMBER; v_r NUMBER; v_p NUMBER; v_antes NUMBER; v_despues NUMBER; v_ok BOOLEAN:=FALSE;
BEGIN
 SELECT h.ID_HABITACION INTO v_h FROM HABITACION h WHERE h.ACTIVA='S' AND NOT EXISTS(
  SELECT 1 FROM RESERVA_HABITACION d JOIN RESERVA r ON r.ID_RESERVA=d.ID_RESERVA
  WHERE d.ID_HABITACION=h.ID_HABITACION AND r.ESTADO IN ('CONFIRMADA','COMPLETADA')
  AND d.FECHA_CHECKIN<DATE '2026-12-12' AND d.FECHA_CHECKOUT>DATE '2026-12-10')
 ORDER BY h.ID_HABITACION FETCH FIRST 1 ROW ONLY;
 SP_RESERVA_PAGO_ATOMICA(1,v_h,DATE '2026-12-10',DATE '2026-12-12',1,50000,'PSE',v_r,v_p);
 INSERT INTO E3_DEMO_TX VALUES('POSTERIOR_AL_SAVEPOINT',v_r,v_p);
 SELECT COUNT(*) INTO v_antes FROM RESERVA;
 SELECT h.ID_HABITACION INTO v_h FROM HABITACION h WHERE h.ACTIVA='S' AND NOT EXISTS(
  SELECT 1 FROM RESERVA_HABITACION d JOIN RESERVA r ON r.ID_RESERVA=d.ID_RESERVA
  WHERE d.ID_HABITACION=h.ID_HABITACION AND r.ESTADO IN ('CONFIRMADA','COMPLETADA')
  AND d.FECHA_CHECKIN<DATE '2026-12-12' AND d.FECHA_CHECKOUT>DATE '2026-12-10')
 ORDER BY h.ID_HABITACION FETCH FIRST 1 ROW ONLY;
 -- OUT no se copia al llamador si el procedimiento termina con excepcion.
 v_r:=NULL;v_p:=NULL;
 BEGIN
  SP_RESERVA_PAGO_ATOMICA(1,v_h,DATE '2026-12-10',DATE '2026-12-12',1,0,'PSE',v_r,v_p);
 EXCEPTION WHEN OTHERS THEN
  IF SQLCODE<>-20101 THEN RAISE; END IF; v_ok:=TRUE;
 END;
 SELECT COUNT(*) INTO v_despues FROM RESERVA;
 IF NOT v_ok OR v_antes<>v_despues OR v_r IS NOT NULL OR v_p IS NOT NULL THEN
  RAISE_APPLICATION_ERROR(-20990,'Fallo de atomicidad');
 END IF;
 DBMS_OUTPUT.PUT_LINE('ORA-20101 esperado; sin reserva ni pago residuales. Se conserva la operacion valida anterior.');
END;
/
-- FIGURA 3.3
ROLLBACK TO e3_parcial;
SELECT 'ROLLBACK TO E3_PARCIAL ejecutado' RESULTADO FROM DUAL;
-- FIGURA 3.4: persisten marcador Y reserva/pago previos; desaparece la segunda operacion.
SELECT d.ETIQUETA,r.ID_RESERVA,p.ID_PAGO,p.MONTO FROM E3_DEMO_TX d
LEFT JOIN RESERVA r ON r.ID_RESERVA=d.ID_RESERVA LEFT JOIN PAGO p ON p.ID_PAGO=d.ID_PAGO;
SELECT COUNT(*) TOTAL_RESERVAS FROM RESERVA;
ROLLBACK TO e3_inicio;
