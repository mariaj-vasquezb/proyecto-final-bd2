CREATE OR REPLACE PACKAGE BODY PKG_REGLAS_TURISMOUQ AS
  PROCEDURE BLOQUEAR IS
    v_id NUMBER;
  BEGIN
    SELECT ID_CONTROL INTO v_id FROM CONTROL_INTEGRIDAD
    WHERE ID_CONTROL = 1 FOR UPDATE;
  END;

  PROCEDURE VALIDAR_PAGOS(p_id NUMBER) IS
    v_estado RESERVA.ESTADO%TYPE;
    v_entrada DATE;
    v_cancelacion DATE;
    v_errores NUMBER;
    v_factor NUMBER := 0;
  BEGIN
    SELECT ESTADO, FECHA_CHECKIN, FECHA_CANCELACION
    INTO v_estado, v_entrada, v_cancelacion FROM RESERVA WHERE ID_RESERVA=p_id;
    IF v_estado='CANCELADA' AND v_entrada-v_cancelacion>5 THEN v_factor:=.8; END IF;
    SELECT COUNT(*) INTO v_errores FROM PAGO
    WHERE ID_RESERVA=p_id AND (
      (v_estado<>'CANCELADA' AND MONTO_REEMBOLSADO<>0) OR
      (v_estado='CANCELADA' AND ESTADO IN ('EXITOSO','REEMBOLSADO')
        AND MONTO_REEMBOLSADO<>ROUND(MONTO*v_factor,2)) OR
      (v_estado='CANCELADA' AND FECHA_PAGO>v_cancelacion));
    IF v_errores>0 THEN
      RAISE_APPLICATION_ERROR(-20044,'Pago o reembolso incompatible con la cancelacion');
    END IF;
  END;

  PROCEDURE APLICAR_CANCELACION(p_id NUMBER) IS
    v_factor NUMBER;
  BEGIN
    SELECT CASE WHEN FECHA_CHECKIN-FECHA_CANCELACION>5 THEN .8 ELSE 0 END
    INTO v_factor FROM RESERVA WHERE ID_RESERVA=p_id;
    UPDATE PAGO SET MONTO_REEMBOLSADO=ROUND(MONTO*v_factor,2),
      ESTADO=CASE WHEN ROUND(MONTO*v_factor,2)>0 THEN 'REEMBOLSADO' ELSE 'EXITOSO' END
    WHERE ID_RESERVA=p_id AND ESTADO='EXITOSO';
  END;

  PROCEDURE VALIDAR_RESERVA(p_id NUMBER) IS
    v_r RESERVA%ROWTYPE;
    v_n NUMBER;
    v_valor NUMBER;
  BEGIN
    BEGIN SELECT * INTO v_r FROM RESERVA WHERE ID_RESERVA=p_id;
    EXCEPTION WHEN NO_DATA_FOUND THEN RETURN; END;
    SELECT COUNT(*) INTO v_n FROM RESERVA_HABITACION WHERE ID_RESERVA=p_id;
    IF v_r.ESTADO IN ('CONFIRMADA','COMPLETADA') AND v_n=0 THEN
      RAISE_APPLICATION_ERROR(-20030,'Una reserva activa requiere al menos una habitacion');
    END IF;
    SELECT COUNT(*) INTO v_n FROM RESERVA_HABITACION rh
    JOIN HABITACION h ON h.ID_HABITACION=rh.ID_HABITACION
    WHERE rh.ID_RESERVA=p_id AND (rh.NUM_HUESPEDES>h.CAPACIDAD OR
      (v_r.ESTADO='CONFIRMADA' AND rh.FECHA_CHECKOUT>TRUNC(SYSDATE) AND h.ACTIVA<>'S'));
    IF v_n>0 THEN RAISE_APPLICATION_ERROR(-20031,'Capacidad excedida o habitacion inactiva'); END IF;
    SELECT COUNT(*) INTO v_n FROM RESERVA_HABITACION
    WHERE ID_RESERVA=p_id AND
      (FECHA_CHECKIN<v_r.FECHA_CHECKIN OR FECHA_CHECKOUT>v_r.FECHA_CHECKOUT);
    IF v_n>0 THEN RAISE_APPLICATION_ERROR(-20032,'Detalle fuera del rango de la reserva'); END IF;
    SELECT COUNT(DISTINCT h.ID_ALOJAMIENTO) INTO v_n
    FROM RESERVA_HABITACION rh JOIN HABITACION h ON h.ID_HABITACION=rh.ID_HABITACION
    WHERE rh.ID_RESERVA=p_id;
    IF v_n>1 THEN RAISE_APPLICATION_ERROR(-20033,'Todas las habitaciones deben ser del mismo alojamiento'); END IF;
    SELECT COUNT(*) INTO v_n FROM RESERVA_SERVICIO rs
    JOIN SERVICIO s ON s.ID_SERVICIO=rs.ID_SERVICIO WHERE rs.ID_RESERVA=p_id
    AND NOT EXISTS (SELECT 1 FROM RESERVA_HABITACION rh
      JOIN HABITACION h ON h.ID_HABITACION=rh.ID_HABITACION
      WHERE rh.ID_RESERVA=p_id AND h.ID_ALOJAMIENTO=s.ID_ALOJAMIENTO);
    IF v_n>0 THEN RAISE_APPLICATION_ERROR(-20034,'Servicio ajeno al alojamiento de la reserva'); END IF;
    SELECT COUNT(*) INTO v_n FROM RESENA re WHERE re.ID_RESERVA=p_id AND
      (v_r.ESTADO<>'COMPLETADA' OR NOT EXISTS (
        SELECT 1 FROM RESERVA_HABITACION rh JOIN HABITACION h ON h.ID_HABITACION=rh.ID_HABITACION
        WHERE rh.ID_RESERVA=p_id AND h.ID_ALOJAMIENTO=re.ID_ALOJAMIENTO)
       OR re.FECHA_RESENA<(SELECT MAX(rh.FECHA_CHECKOUT) FROM RESERVA_HABITACION rh
          JOIN HABITACION h ON h.ID_HABITACION=rh.ID_HABITACION
          WHERE rh.ID_RESERVA=p_id AND h.ID_ALOJAMIENTO=re.ID_ALOJAMIENTO));
    IF v_n>0 THEN RAISE_APPLICATION_ERROR(-20035,'Resena sin estadia completada valida'); END IF;
    IF v_r.ESTADO IN ('CONFIRMADA','COMPLETADA') THEN
      SELECT COUNT(*) INTO v_n FROM RESERVA_HABITACION a
      JOIN RESERVA_HABITACION b ON b.ID_HABITACION=a.ID_HABITACION
        AND b.ID_RESERVA_HAB<>a.ID_RESERVA_HAB
      JOIN RESERVA r ON r.ID_RESERVA=b.ID_RESERVA
      WHERE a.ID_RESERVA=p_id AND r.ESTADO IN ('CONFIRMADA','COMPLETADA')
        AND a.FECHA_CHECKIN<b.FECHA_CHECKOUT AND a.FECHA_CHECKOUT>b.FECHA_CHECKIN;
      IF v_n>0 THEN RAISE_APPLICATION_ERROR(-20026,'Habitacion ocupada: reserva confirmada solapada'); END IF;
      FOR d IN (SELECT ID_HABITACION,FECHA_CHECKIN,FECHA_CHECKOUT FROM RESERVA_HABITACION WHERE ID_RESERVA=p_id) LOOP
        v_valor:=PKG_TURISMOUQ.FN_VALOR_ESTADIA(d.ID_HABITACION,d.FECHA_CHECKIN,d.FECHA_CHECKOUT);
      END LOOP;
    END IF;
    VALIDAR_PAGOS(p_id);
  END;

  PROCEDURE VALIDAR_CALENDARIO IS
    v_n NUMBER;
  BEGIN
    SELECT COUNT(*) INTO v_n FROM TEMPORADA a JOIN TEMPORADA b
      ON b.ID_TEMPORADA>a.ID_TEMPORADA AND a.FECHA_INICIO<=b.FECHA_FIN AND a.FECHA_FIN>=b.FECHA_INICIO;
    IF v_n>0 THEN RAISE_APPLICATION_ERROR(-20036,'Temporadas solapadas'); END IF;
  END;
END PKG_REGLAS_TURISMOUQ;
