-- Calendario turistico 2024-2026. Periodos continuos, inclusivos, sin solapes.
-- ALTA: 15 dic-15 ene, 15 jun-31 jul, Semana Santa (domingo a domingo)
-- y viernes-lunes de festivos que caen/se trasladan a lunes.
-- MEDIA: resto de marzo/abril/octubre/noviembre. BAJA: los demas dias.
-- El calendario es una convencion de negocio para los datos sinteticos.
DECLARE
  v_dia DATE;
  v_inicio DATE:=DATE '2024-01-01';
  v_tipo VARCHAR2(10);
  v_anterior VARCHAR2(10);
  v_id NUMBER:=0;
  FUNCTION lunes(p_d DATE) RETURN DATE IS
  BEGIN
    IF p_d=TRUNC(p_d,'IW') THEN RETURN p_d; END IF;
    RETURN TRUNC(p_d,'IW')+7;
  END;
  FUNCTION tipo_dia(p_d DATE) RETURN VARCHAR2 IS
    v_y NUMBER:=EXTRACT(YEAR FROM p_d);
    v_ini DATE:=TRUNC(p_d,'YYYY');
    v_pascua DATE;
    TYPE t_fechas IS TABLE OF DATE;
    v_fiestas t_fechas;
  BEGIN
    v_pascua:=CASE v_y WHEN 2024 THEN DATE '2024-03-31'
      WHEN 2025 THEN DATE '2025-04-20' ELSE DATE '2026-04-05' END;
    IF TO_CHAR(p_d,'MMDD')>='1215' OR TO_CHAR(p_d,'MMDD')<='0115'
       OR (TO_CHAR(p_d,'MMDD') BETWEEN '0615' AND '0731')
       OR p_d BETWEEN v_pascua-7 AND v_pascua THEN RETURN 'ALTA'; END IF;
    v_fiestas:=t_fechas(v_ini, v_ini+120,
      ADD_MONTHS(v_ini,6)+19, ADD_MONTHS(v_ini,7)+6,
      ADD_MONTHS(v_ini,11)+7, ADD_MONTHS(v_ini,11)+24,
      lunes(v_ini+5),lunes(ADD_MONTHS(v_ini,2)+18),
      lunes(ADD_MONTHS(v_ini,5)+28),lunes(ADD_MONTHS(v_ini,7)+14),
      lunes(ADD_MONTHS(v_ini,9)+11),lunes(ADD_MONTHS(v_ini,10)),
      lunes(ADD_MONTHS(v_ini,10)+10),v_pascua+43,v_pascua+64,v_pascua+71);
    -- El primero de mayo se expresa por mes para respetar anos bisiestos.
    v_fiestas(2):=ADD_MONTHS(v_ini,4);
    FOR j IN 1..v_fiestas.COUNT LOOP
      IF v_fiestas(j)=TRUNC(v_fiestas(j),'IW')
         AND p_d BETWEEN v_fiestas(j)-3 AND v_fiestas(j) THEN RETURN 'ALTA'; END IF;
    END LOOP;
    IF EXTRACT(MONTH FROM p_d) IN (3,4,10,11) THEN RETURN 'MEDIA'; END IF;
    RETURN 'BAJA';
  END;
  PROCEDURE guardar(p_fin DATE) IS
  BEGIN
    v_id:=v_id+1;
    INSERT INTO TEMPORADA(ID_TEMPORADA,NOMBRE,TIPO,FECHA_INICIO,FECHA_FIN)
    VALUES(v_id,v_anterior||' desde '||TO_CHAR(v_inicio,'YYYY-MM-DD'),v_anterior,v_inicio,p_fin);
  END;
BEGIN
  FOR d IN 0..(DATE '2027-01-01'-DATE '2024-01-01'-1) LOOP
    v_dia:=DATE '2024-01-01'+d; v_tipo:=tipo_dia(v_dia);
    IF v_anterior IS NULL THEN v_anterior:=v_tipo;
    ELSIF v_tipo<>v_anterior OR TRUNC(v_dia,'YYYY')<>TRUNC(v_inicio,'YYYY') THEN
      guardar(v_dia-1); v_inicio:=v_dia; v_anterior:=v_tipo;
    END IF;
  END LOOP;
  guardar(DATE '2026-12-31');
END;
