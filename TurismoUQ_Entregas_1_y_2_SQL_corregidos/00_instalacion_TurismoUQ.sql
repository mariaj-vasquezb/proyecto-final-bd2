  v_in DATE; v_out DATE; v_estado VARCHAR2(12);
  v_total NUMBER; v_monto NUMBER; v_reembolso NUMBER;
  v_servicio1 NUMBER; v_servicio2 NUMBER; v_cant NUMBER;
  v_cancelacion DATE; v_factor NUMBER;
  v_corte CONSTANT DATE:=DATE '2026-11-13';
BEGIN
  FOR c IN (
    WITH slots AS (
      SELECT LEVEL-1 n FROM DUAL CONNECT BY LEVEL<=157
    ), principales AS (
      SELECT h.*,MAX(ID_HABITACION) OVER (PARTITION BY ID_ALOJAMIENTO) auxiliar,
        MIN(ID_HABITACION) OVER (PARTITION BY ID_ALOJAMIENTO) primera
      FROM HABITACION h
    ), candidatos AS (
      SELECT h.ID_HABITACION,h.ID_ALOJAMIENTO,h.auxiliar,h.primera,s.n,
        DATE '2024-01-01'+s.n*7+MOD(h.ID_HABITACION,3) entrada,
        DATE '2024-01-01'+s.n*7+MOD(h.ID_HABITACION,3)+2+MOD(h.ID_HABITACION+s.n,4) salida
      FROM principales h CROSS JOIN slots s WHERE h.ID_HABITACION<>h.auxiliar
    ), ponderados AS (
      SELECT c.*,MOD(c.ID_HABITACION*7919+c.n*104729+c.ID_HABITACION*c.n*37,1000003)/
        CASE t.TIPO WHEN 'ALTA' THEN 3 WHEN 'MEDIA' THEN 1.6 ELSE 1 END prioridad
      FROM candidatos c JOIN TEMPORADA t ON c.entrada BETWEEN t.FECHA_INICIO AND t.FECHA_FIN
      WHERE c.salida<=DATE '2027-01-01'
    ), elegidos AS (
      SELECT * FROM ponderados ORDER BY prioridad,entrada,ID_HABITACION FETCH FIRST 25000 ROWS ONLY
    )
    SELECT * FROM elegidos ORDER BY entrada,ID_HABITACION
  ) LOOP
    v_i:=v_i+1; v_in:=c.entrada; v_out:=c.salida;
    v_estado:=CASE WHEN MOD(v_i+c.n*7+c.ID_HABITACION*3,20) IN (0,1) THEN 'CANCELADA'
      WHEN MOD(v_i+c.n*7+c.ID_HABITACION*3,20) IN (2,3) THEN 'PENDIENTE'
      WHEN MOD(v_i+c.n*7+c.ID_HABITACION*3,20) IN (4,5,6) THEN 'CONFIRMADA' ELSE 'COMPLETADA' END;
    IF v_estado='COMPLETADA' AND v_out>v_corte THEN v_estado:='CONFIRMADA'; END IF;
    v_cancelacion:=NULL; v_factor:=0;
    IF v_estado='CANCELADA' THEN
      v_cancelacion:=LEAST(v_in-CASE WHEN MOD(v_i,2)=0 THEN 6 ELSE 3 END,v_corte);
      IF v_in-v_cancelacion>5 THEN v_factor:=.8; END IF;
    END IF;
    INSERT INTO RESERVA(ID_RESERVA,ID_CLIENTE,FECHA_RESERVA,FECHA_CHECKIN,FECHA_CHECKOUT,ESTADO,FECHA_CANCELACION)
    VALUES(v_i,MOD(v_i*17,3000)+1,LEAST(v_in-10,v_corte-10),v_in,v_out,v_estado,v_cancelacion);
    INSERT INTO RESERVA_HABITACION(ID_RESERVA_HAB,ID_RESERVA,ID_HABITACION,FECHA_CHECKIN,FECHA_CHECKOUT,NUM_HUESPEDES)
    VALUES(v_i,v_i,c.ID_HABITACION,v_in,v_out,1);
    IF c.ID_HABITACION=c.primera THEN
      INSERT INTO RESERVA_HABITACION(ID_RESERVA_HAB,ID_RESERVA,ID_HABITACION,FECHA_CHECKIN,FECHA_CHECKOUT,NUM_HUESPEDES)
      VALUES(25000+v_i,v_i,c.auxiliar,v_in,v_out,1);
    END IF;
    SELECT PRECIO INTO v_servicio1 FROM SERVICIO WHERE ID_SERVICIO=2*c.ID_ALOJAMIENTO-1;
    SELECT PRECIO INTO v_servicio2 FROM SERVICIO WHERE ID_SERVICIO=2*c.ID_ALOJAMIENTO;
    v_cant:=1+MOD(v_i,3);
    INSERT INTO RESERVA_SERVICIO(ID_RESERVA_SERVICIO,ID_RESERVA,ID_SERVICIO,CANTIDAD,PRECIO_UNITARIO)
    VALUES(v_i,v_i,2*c.ID_ALOJAMIENTO-1,v_cant,v_servicio1);
    IF v_i<=15000 THEN
      INSERT INTO RESERVA_SERVICIO(ID_RESERVA_SERVICIO,ID_RESERVA,ID_SERVICIO,CANTIDAD,PRECIO_UNITARIO)
      VALUES(25000+v_i,v_i,2*c.ID_ALOJAMIENTO,1,v_servicio2);
    END IF;
    -- Se consulta TARIFA: no se duplica su formula en el calculo de pagos.
    SELECT SUM(p.PRECIO_NOCHE*(LEAST(v_out,t.FECHA_FIN+1)-GREATEST(v_in,t.FECHA_INICIO)))
    INTO v_total FROM TARIFA p JOIN TEMPORADA t ON t.ID_TEMPORADA=p.ID_TEMPORADA
    WHERE (p.ID_HABITACION=c.ID_HABITACION OR
      (c.ID_HABITACION=c.primera AND p.ID_HABITACION=c.auxiliar))
      AND t.FECHA_INICIO<v_out AND t.FECHA_FIN>=v_in;
    v_total:=v_total+v_cant*v_servicio1;
    IF v_i<=15000 THEN v_total:=v_total+v_servicio2; END IF;
    v_monto:=CASE WHEN v_i<=5000 THEN ROUND(v_total*.4,2) ELSE v_total END;
    v_reembolso:=ROUND(v_monto*v_factor,2);
    INSERT INTO PAGO(ID_PAGO,ID_RESERVA,FECHA_PAGO,MONTO,MONTO_REEMBOLSADO,METODO,ESTADO)
    VALUES(v_i,v_i,LEAST(v_in-9,v_corte-9),v_monto,v_reembolso,
      CASE MOD(v_i,5) WHEN 0 THEN 'PSE' WHEN 1 THEN 'CREDITO' WHEN 2 THEN 'DEBITO'
        WHEN 3 THEN 'TRANSFERENCIA' ELSE 'EFECTIVO' END,
      CASE WHEN v_reembolso>0 THEN 'REEMBOLSADO' WHEN v_estado='PENDIENTE' THEN 'PENDIENTE' ELSE 'EXITOSO' END);
    IF v_i<=5000 THEN
      v_monto:=ROUND(v_total*.6,2); v_reembolso:=ROUND(v_monto*v_factor,2);
      INSERT INTO PAGO(ID_PAGO,ID_RESERVA,FECHA_PAGO,MONTO,MONTO_REEMBOLSADO,METODO,ESTADO)
      VALUES(25000+v_i,v_i,LEAST(v_in-8,v_corte-8),v_monto,v_reembolso,'PSE',
        CASE WHEN v_reembolso>0 THEN 'REEMBOLSADO' WHEN v_estado='PENDIENTE' THEN 'PENDIENTE' ELSE 'EXITOSO' END);
    END IF;
    -- Una resena por cada dos estadias completadas; nunca antes del checkout.
    IF v_estado='COMPLETADA' THEN
      v_completadas:=v_completadas+1;
      IF MOD(v_completadas,2)=0 AND v_out+1<=v_corte THEN
        INSERT INTO RESENA(ID_RESENA,ID_RESERVA,ID_ALOJAMIENTO,CALIFICACION,COMENTARIO,FECHA_RESENA)
        VALUES(v_i,v_i,c.ID_ALOJAMIENTO,MOD(v_i+c.ID_HABITACION,5)+1,'Experiencia turistica de prueba '||v_i,v_out+1);
      END IF;
    END IF;
  END LOOP;
  IF v_i<>25000 THEN RAISE_APPLICATION_ERROR(-20070,'No se generaron 25000 reservas'); END IF;
END;
