-- Actualizacion manual de la vista (ejecutar separado)
ALTER MATERIALIZED VIEW MV_OCUPACION_MENSUAL COMPILE;
BEGIN
    DBMS_MVIEW.REFRESH('MV_OCUPACION_MENSUAL', 'C');
END;
