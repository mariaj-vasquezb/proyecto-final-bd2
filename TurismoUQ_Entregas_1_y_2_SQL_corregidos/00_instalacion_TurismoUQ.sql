-- Colecciones locales al statement: no consultan RESERVA durante su fase por fila.
CREATE OR REPLACE TRIGGER TRG_REGLAS_RESERVA
FOR INSERT OR UPDATE OR DELETE ON RESERVA COMPOUND TRIGGER
  TYPE t_ids IS TABLE OF BOOLEAN INDEX BY PLS_INTEGER;
  g_ids t_ids;
  g_canceladas t_ids;
  BEFORE STATEMENT IS BEGIN PKG_REGLAS_TURISMOUQ.BLOQUEAR; END BEFORE STATEMENT;
  BEFORE EACH ROW IS
  BEGIN
    IF UPDATING THEN
      IF :NEW.ID_RESERVA<>:OLD.ID_RESERVA THEN
        RAISE_APPLICATION_ERROR(-20037,'No se modifica el identificador de una reserva');
      END IF;
      IF :OLD.ESTADO IN ('CANCELADA','COMPLETADA') AND :NEW.ESTADO<>:OLD.ESTADO THEN
        RAISE_APPLICATION_ERROR(-20037,'Cancelada y completada son estados finales');
      END IF;
      IF :OLD.ESTADO='COMPLETADA' AND :NEW.ID_CLIENTE<>:OLD.ID_CLIENTE THEN
        RAISE_APPLICATION_ERROR(-20037,'No se cambia el cliente de una estadia completada');
      END IF;
      IF :OLD.ESTADO='CANCELADA' AND :NEW.FECHA_CANCELACION<>:OLD.FECHA_CANCELACION THEN
        RAISE_APPLICATION_ERROR(-20037,'La fecha de cancelacion es inmutable');
      END IF;
    END IF;
    IF NOT DELETING THEN
      IF :NEW.ESTADO='CANCELADA' THEN
        :NEW.FECHA_CANCELACION:=NVL(:NEW.FECHA_CANCELACION,SYSDATE);
        IF :NEW.FECHA_CANCELACION<:NEW.FECHA_RESERVA OR :NEW.FECHA_CANCELACION>:NEW.FECHA_CHECKIN THEN
          RAISE_APPLICATION_ERROR(-20038,'Cancelacion fuera del periodo permitido');
        END IF;
      ELSIF :NEW.FECHA_CANCELACION IS NOT NULL THEN
        RAISE_APPLICATION_ERROR(-20038,'Solo una reserva cancelada tiene fecha de cancelacion');
      END IF;
      IF :NEW.ESTADO='COMPLETADA' AND :NEW.FECHA_CHECKOUT>TRUNC(SYSDATE) THEN
        RAISE_APPLICATION_ERROR(-20038,'No se completa una estadia que aun no termina');
      END IF;
    END IF;
  END BEFORE EACH ROW;
  AFTER EACH ROW IS
  BEGIN
    IF NOT DELETING THEN
      g_ids(:NEW.ID_RESERVA):=TRUE;
      IF :NEW.ESTADO='CANCELADA' AND (INSERTING OR :OLD.ESTADO<>'CANCELADA') THEN
        g_canceladas(:NEW.ID_RESERVA):=TRUE;
      END IF;
    END IF;
  END AFTER EACH ROW;
  AFTER STATEMENT IS
    v_id PLS_INTEGER;
  BEGIN
    v_id:=g_canceladas.FIRST;
    WHILE v_id IS NOT NULL LOOP
      PKG_REGLAS_TURISMOUQ.APLICAR_CANCELACION(v_id); v_id:=g_canceladas.NEXT(v_id);
    END LOOP;
    v_id:=g_ids.FIRST;
    WHILE v_id IS NOT NULL LOOP
      PKG_REGLAS_TURISMOUQ.VALIDAR_RESERVA(v_id); v_id:=g_ids.NEXT(v_id);
    END LOOP;
  END AFTER STATEMENT;
END TRG_REGLAS_RESERVA;
/

