 CONSTRAINT PK_E3_MEDICION PRIMARY KEY(CASO,FASE)
);
CREATE OR REPLACE PACKAGE PKG_E3_INDICES AS
 PROCEDURE PREPARAR;
 PROCEDURE CREAR_INDICE(p_caso NUMBER);
 PROCEDURE MEDIR(p_caso NUMBER,p_fase VARCHAR2,p_repeticiones NUMBER DEFAULT 500);
END;
