CREATE OR REPLACE PACKAGE BODY PKG_E3_INDICES AS
 FUNCTION consulta(p_caso NUMBER) RETURN VARCHAR2 IS
 BEGIN
  CASE p_caso
  WHEN 1 THEN RETURN 'SELECT /* TQ_E3_Q1 */ SUM(MONTO-MONTO_REEMBOLSADO) FROM PAGO WHERE ID_RESERVA=12345';
  WHEN 2 THEN RETURN 'SELECT /* TQ_E3_Q2 */ SUM(NUM_HUESPEDES) FROM RESERVA_HABITACION WHERE ID_HABITACION=1 AND FECHA_CHECKIN>=DATE ''2026-01-01'' AND FECHA_CHECKIN<DATE ''2026-02-01''';
  WHEN 3 THEN RETURN 'SELECT /* TQ_E3_Q3 */ SUM(MONTO-MONTO_REEMBOLSADO) FROM PAGO WHERE TRUNC(FECHA_PAGO)=DATE ''2026-03-02''';
  WHEN 4 THEN RETURN 'SELECT /* TQ_E3_Q4 */ SUM(MONTO-MONTO_REEMBOLSADO) FROM PAGO WHERE MONTO>0';
  ELSE RAISE_APPLICATION_ERROR(-20301,'Caso de indice invalido'); END CASE;
 END;
 PROCEDURE estadisticas IS BEGIN
  DBMS_STATS.GATHER_TABLE_STATS(USER,'PAGO',cascade=>TRUE,method_opt=>'FOR ALL COLUMNS SIZE 1');
  DBMS_STATS.GATHER_TABLE_STATS(USER,'RESERVA_HABITACION',cascade=>TRUE,method_opt=>'FOR ALL COLUMNS SIZE 1');
 END;
 PROCEDURE PREPARAR IS
 BEGIN
  -- SOLO se eliminan los cuatro indices del experimento; no PK, UNIQUE ni otros.
  FOR r IN(SELECT INDEX_NAME FROM USER_INDEXES WHERE INDEX_NAME IN
   ('IX_E3_PAGO_RESERVA','IX_E3_RH_HAB_FECHA','IX_E3_PAGO_DIA','IX_E3_PAGO_MONTO')) LOOP
   EXECUTE IMMEDIATE 'DROP INDEX '||r.INDEX_NAME;
  END LOOP;
  DELETE FROM E3_MEDICION_INDICES; DELETE FROM E3_PLAN_TABLE; COMMIT;
  estadisticas;
 END;
 PROCEDURE CREAR_INDICE(p_caso NUMBER) IS
 BEGIN
  CASE p_caso
  WHEN 1 THEN EXECUTE IMMEDIATE 'CREATE INDEX IX_E3_PAGO_RESERVA ON PAGO(ID_RESERVA)';
  WHEN 2 THEN EXECUTE IMMEDIATE 'CREATE INDEX IX_E3_RH_HAB_FECHA ON RESERVA_HABITACION(ID_HABITACION,FECHA_CHECKIN)';
  WHEN 3 THEN EXECUTE IMMEDIATE 'CREATE INDEX IX_E3_PAGO_DIA ON PAGO(TRUNC(FECHA_PAGO))';
  WHEN 4 THEN EXECUTE IMMEDIATE 'CREATE INDEX IX_E3_PAGO_MONTO ON PAGO(MONTO)';
  ELSE RAISE_APPLICATION_ERROR(-20301,'Caso de indice invalido'); END CASE;
  estadisticas;
 END;
 PROCEDURE MEDIR(p_caso NUMBER,p_fase VARCHAR2,p_repeticiones NUMBER DEFAULT 500) IS
  v_sql VARCHAR2(2000); v_resultado NUMBER; v_t NUMBER; v_cpu NUMBER;
  v_gets0 NUMBER; v_gets1 NUMBER;
  v_id VARCHAR2(13);v_plan NUMBER;v_child NUMBER; v_stmt VARCHAR2(30);
 BEGIN
  IF p_fase NOT IN ('ANTES','DESPUES') OR p_fase IS NULL OR p_repeticiones IS NULL OR
     p_repeticiones NOT BETWEEN 1 AND 10000 OR p_repeticiones<>TRUNC(p_repeticiones) THEN
   RAISE_APPLICATION_ERROR(-20302,'Fase o repeticiones invalidas');
  END IF;
  v_sql:=consulta(p_caso);v_stmt:='Q'||p_caso||'_'||p_fase;
  DELETE FROM E3_PLAN_TABLE WHERE STATEMENT_ID=v_stmt;
  EXECUTE IMMEDIATE 'EXPLAIN PLAN SET STATEMENT_ID='''||v_stmt||''' INTO E3_PLAN_TABLE FOR '||v_sql;
  EXECUTE IMMEDIATE v_sql INTO v_resultado; -- calentamiento en ambas fases
  SELECT SQL_ID,CHILD_NUMBER,PLAN_HASH_VALUE INTO v_id,v_child,v_plan
  FROM V$SQL WHERE SQL_TEXT=v_sql AND PARSING_SCHEMA_NAME=USER
  ORDER BY LAST_ACTIVE_TIME DESC,CHILD_NUMBER DESC FETCH FIRST 1 ROW ONLY;
  SELECT m.VALUE INTO v_gets0 FROM V$MYSTAT m JOIN V$STATNAME n ON n.STATISTIC#=m.STATISTIC# WHERE n.NAME='session logical reads';
  v_t:=DBMS_UTILITY.GET_TIME;v_cpu:=DBMS_UTILITY.GET_CPU_TIME;
  FOR i IN 1..p_repeticiones LOOP EXECUTE IMMEDIATE v_sql INTO v_resultado; END LOOP;
  v_t:=(DBMS_UTILITY.GET_TIME-v_t)*10;v_cpu:=(DBMS_UTILITY.GET_CPU_TIME-v_cpu)*10;
  SELECT m.VALUE INTO v_gets1 FROM V$MYSTAT m JOIN V$STATNAME n ON n.STATISTIC#=m.STATISTIC# WHERE n.NAME='session logical reads';
  DELETE FROM E3_MEDICION_INDICES WHERE CASO=p_caso AND FASE=p_fase;
  INSERT INTO E3_MEDICION_INDICES(CASO,FASE,REPETICIONES,RESULTADO,TIEMPO_TOTAL_MS,CPU_TOTAL_MS,
   GETS_POR_EJEC,SQL_ID,PLAN_HASH_VALUE)
  VALUES(p_caso,p_fase,p_repeticiones,v_resultado,v_t,v_cpu,
   (v_gets1-v_gets0)/p_repeticiones,v_id,v_plan);
  COMMIT;
  DBMS_OUTPUT.PUT_LINE('Q'||p_caso||' '||p_fase||': '||p_repeticiones||' ejecuciones, '||v_t||' ms; CPU '||v_cpu||' ms');
 END;
END;
