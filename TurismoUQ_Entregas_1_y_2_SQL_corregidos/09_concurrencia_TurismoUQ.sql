CREATE TABLE E3_LAB_HABITACION(ID_HABITACION NUMBER PRIMARY KEY);
INSERT INTO E3_LAB_HABITACION VALUES(1);
CREATE TABLE E3_LAB_RESERVA(
 ID_RESERVA NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 ID_HABITACION NUMBER NOT NULL REFERENCES E3_LAB_HABITACION,
 ENTRADA DATE NOT NULL,SALIDA DATE NOT NULL,SESION VARCHAR2(30),
 CONSTRAINT CK_E3_LAB_FECHAS CHECK(SALIDA>ENTRADA)
);
CREATE TABLE E3_LAB_RESULTADO(ESCENARIO VARCHAR2(20) PRIMARY KEY,RESERVAS NUMBER);
COMMIT;
CREATE OR REPLACE PROCEDURE SP_E3_RESERVAR_LAB(p_sesion VARCHAR2,p_bloquear NUMBER) IS
 v_n NUMBER; v_id NUMBER;
BEGIN
 IF p_bloquear NOT IN (0,1) OR p_bloquear IS NULL THEN RAISE_APPLICATION_ERROR(-20202,'Modo invalido'); END IF;
 IF p_bloquear=1 THEN
  SELECT ID_HABITACION INTO v_id FROM E3_LAB_HABITACION WHERE ID_HABITACION=1 FOR UPDATE;
 END IF;
 SELECT COUNT(*) INTO v_n FROM E3_LAB_RESERVA
 WHERE ID_HABITACION=1 AND ENTRADA<DATE '2026-12-12' AND SALIDA>DATE '2026-12-10';
 IF v_n>0 THEN RAISE_APPLICATION_ERROR(-20201,'Habitacion de laboratorio ocupada'); END IF;
 INSERT INTO E3_LAB_RESERVA(ID_HABITACION,ENTRADA,SALIDA,SESION)
 VALUES(1,DATE '2026-12-10',DATE '2026-12-12',p_sesion);
 DBMS_OUTPUT.PUT_LINE('Sesion '||p_sesion||': reserva insertada, sin COMMIT; bloqueo='||p_bloquear);
END;
