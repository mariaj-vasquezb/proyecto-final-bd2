-- Sincronizar las identidades: las cargas anteriores usaron ID explicitos.
-- START WITH LIMIT VALUE hace que los INSERT posteriores sin ID no choquen.
DECLARE
  v_ddl VARCHAR2(1000);
BEGIN
  FOR r IN (SELECT TABLE_NAME, COLUMN_NAME
              FROM USER_TAB_IDENTITY_COLS
             WHERE TABLE_NAME IN
               ('MUNICIPIO','TIPO_ALOJAMIENTO','ALOJAMIENTO','HABITACION',
                'TEMPORADA','TARIFA','CLIENTE','RESERVA','RESERVA_HABITACION',
                'PAGO','SERVICIO','RESERVA_SERVICIO','RESENA','USUARIO_SISTEMA')) LOOP
    v_ddl:='ALTER TABLE '||r.TABLE_NAME||' MODIFY ('||r.COLUMN_NAME||
           ' GENERATED BY DEFAULT ON NULL AS IDENTITY (START WITH LIMIT VALUE))';
    EXECUTE IMMEDIATE v_ddl;
  END LOOP;
END;
