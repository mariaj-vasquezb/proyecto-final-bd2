  v_tipos t_nombres := t_nombres('Finca cafetera','Hotel','Glamping','Hostal');
  v_mun NUMBER;
  v_tipo NUMBER;
  v_hab NUMBER := 0;
  v_cantidad NUMBER;
  v_aloj NUMBER;
BEGIN
  FOR i IN 1..12 LOOP
    INSERT INTO MUNICIPIO (ID_MUNICIPIO,NOMBRE) VALUES (i,v_municipios(i));
  END LOOP;
  FOR i IN 1..4 LOOP
    INSERT INTO TIPO_ALOJAMIENTO (ID_TIPO,NOMBRE,DESCRIPCION)
    VALUES (i,v_tipos(i),'Categoria de alojamiento para la plataforma TurismoUQ');
  END LOOP;
  FOR i IN 1..60 LOOP
    -- Reparto desigual: Armenia concentra mas hoteles, otros municipios menos.
    v_mun := CASE WHEN i <= 12 THEN 1 WHEN i <= 20 THEN 9 WHEN i <= 26 THEN 12
                  ELSE MOD(i*7,11)+2 END;
    v_tipo := CASE WHEN i<=4 THEN 2 WHEN i<=10 THEN 2
                   ELSE MOD(i,4)+1 END;
    INSERT INTO ALOJAMIENTO (ID_ALOJAMIENTO,ID_MUNICIPIO,ID_TIPO,NOMBRE,DIRECCION,ESTRELLAS,TELEFONO,CORREO)
    VALUES (i,v_mun,v_tipo,'TurismoUQ Alojamiento '||TO_CHAR(i,'FM000'),
            'Carrera '||i||' No. '||(i+5)||'-10',MOD(i,5)+1,
            '606700'||TO_CHAR(i,'FM0000'),'alojamiento'||i||'@turismouq.example');
    v_cantidad := CASE WHEN i<=4 THEN 35 WHEN i<=10 THEN 15
                       WHEN i<=30 THEN 4 ELSE 3 END;
    FOR j IN 1..v_cantidad LOOP
      v_hab := v_hab+1;
      INSERT INTO HABITACION(ID_HABITACION,ID_ALOJAMIENTO,NUMERO,CAPACIDAD,TIPO,DESCRIPCION,ACTIVA)
      VALUES(v_hab,i,TO_CHAR(j,'FM000'),MOD(j,4)+1,
             CASE MOD(j,4) WHEN 0 THEN 'SUITE' WHEN 1 THEN 'SENCILLA'
                           WHEN 2 THEN 'DOBLE' ELSE 'CABANA' END,
             'Habitacion '||j||' del alojamiento '||i,'S');
    END LOOP;
    -- Dos servicios por alojamiento (120 en total).
    INSERT INTO SERVICIO(ID_SERVICIO,ID_ALOJAMIENTO,NOMBRE,DESCRIPCION,PRECIO)
    VALUES (2*i-1,i,'Desayuno','Desayuno local',15000+MOD(i,5)*2000);
    INSERT INTO SERVICIO(ID_SERVICIO,ID_ALOJAMIENTO,NOMBRE,DESCRIPCION,PRECIO)
    VALUES (2*i,i,'Tour guiado','Recorrido turistico del Quindio',45000+MOD(i,7)*5000);
  END LOOP;
  DBMS_OUTPUT.PUT_LINE('Habitaciones cargadas: '||v_hab);
