-- 1. Catálogo de municipios del Quindío
CREATE TABLE MUNICIPIO (
  ID_MUNICIPIO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  NOMBRE VARCHAR2(80) NOT NULL,
  CONSTRAINT PK_MUNICIPIO PRIMARY KEY (ID_MUNICIPIO),
  CONSTRAINT UQ_MUNICIPIO_NOMBRE UNIQUE (NOMBRE)
);

-- 2. Tipos de alojamiento
CREATE TABLE TIPO_ALOJAMIENTO (
  ID_TIPO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  NOMBRE VARCHAR2(60) NOT NULL,
  DESCRIPCION VARCHAR2(250),
  CONSTRAINT PK_TIPO_ALOJAMIENTO PRIMARY KEY (ID_TIPO),
  CONSTRAINT UQ_TIPO_ALOJAMIENTO UNIQUE (NOMBRE)
);

-- 3. Alojamientos por municipio y tipo
CREATE TABLE ALOJAMIENTO (
  ID_ALOJAMIENTO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  ID_MUNICIPIO NUMBER NOT NULL,
  ID_TIPO NUMBER NOT NULL,
  NOMBRE VARCHAR2(150) NOT NULL,
  DIRECCION VARCHAR2(250) NOT NULL,
  ESTRELLAS NUMBER(1) DEFAULT 3 NOT NULL,
  TELEFONO VARCHAR2(30),
  CORREO VARCHAR2(150),
  CONSTRAINT PK_ALOJAMIENTO PRIMARY KEY (ID_ALOJAMIENTO),
  CONSTRAINT FK_ALO_MUNICIPIO FOREIGN KEY (ID_MUNICIPIO) REFERENCES MUNICIPIO(ID_MUNICIPIO),
  CONSTRAINT FK_ALO_TIPO FOREIGN KEY (ID_TIPO) REFERENCES TIPO_ALOJAMIENTO(ID_TIPO),
  CONSTRAINT CK_ALO_ESTRELLAS CHECK (ESTRELLAS BETWEEN 1 AND 5)
);

-- 4. Habitaciones; número único dentro del mismo alojamiento
CREATE TABLE HABITACION (
  ID_HABITACION NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  ID_ALOJAMIENTO NUMBER NOT NULL,
  NUMERO VARCHAR2(15) NOT NULL,
  CAPACIDAD NUMBER(3) NOT NULL,
  TIPO VARCHAR2(30) NOT NULL,
  DESCRIPCION VARCHAR2(500),
  ACTIVA CHAR(1) DEFAULT 'S' NOT NULL,
  CONSTRAINT PK_HABITACION PRIMARY KEY (ID_HABITACION),
  CONSTRAINT FK_HAB_ALO FOREIGN KEY (ID_ALOJAMIENTO) REFERENCES ALOJAMIENTO(ID_ALOJAMIENTO),
  CONSTRAINT UQ_HAB_ALO_NUM UNIQUE (ID_ALOJAMIENTO, NUMERO),
  CONSTRAINT CK_HAB_CAPACIDAD CHECK (CAPACIDAD > 0),
  CONSTRAINT CK_HAB_ACTIVA CHECK (ACTIVA IN ('S','N'))
);

-- 5. Periodos tarifarios fechados por año (alta/media/baja)
CREATE TABLE TEMPORADA (
  ID_TEMPORADA NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  NOMBRE VARCHAR2(80) NOT NULL,
  TIPO VARCHAR2(10) NOT NULL,
  FECHA_INICIO DATE NOT NULL,
  FECHA_FIN DATE NOT NULL,
  CONSTRAINT PK_TEMPORADA PRIMARY KEY (ID_TEMPORADA),
  CONSTRAINT CK_TEMP_TIPO CHECK (TIPO IN ('ALTA','MEDIA','BAJA')),
  CONSTRAINT CK_TEMP_FECHAS CHECK (FECHA_FIN >= FECHA_INICIO),
  CONSTRAINT UQ_TEMP_PERIODO UNIQUE (NOMBRE, FECHA_INICIO),
  CONSTRAINT CK_TEMP_DIAS CHECK (FECHA_INICIO = TRUNC(FECHA_INICIO) AND FECHA_FIN = TRUNC(FECHA_FIN)),
  CONSTRAINT CK_TEMP_ANIO CHECK (TRUNC(FECHA_INICIO,'YYYY') = TRUNC(FECHA_FIN,'YYYY'))
);

-- 6. Precio por habitación y temporada
CREATE TABLE TARIFA (
  ID_TARIFA NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  ID_HABITACION NUMBER NOT NULL,
  ID_TEMPORADA NUMBER NOT NULL,
  PRECIO_NOCHE NUMBER(12,2) NOT NULL,
  CONSTRAINT PK_TARIFA PRIMARY KEY (ID_TARIFA),
  CONSTRAINT FK_TAR_HAB FOREIGN KEY (ID_HABITACION) REFERENCES HABITACION(ID_HABITACION),
  CONSTRAINT FK_TAR_TEMP FOREIGN KEY (ID_TEMPORADA) REFERENCES TEMPORADA(ID_TEMPORADA),
  CONSTRAINT UQ_TAR_HAB_TEMP UNIQUE (ID_HABITACION, ID_TEMPORADA),
  CONSTRAINT CK_TAR_PRECIO CHECK (PRECIO_NOCHE > 0)
);

-- 7. Clientes
CREATE TABLE CLIENTE (
  ID_CLIENTE NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  NOMBRE VARCHAR2(120) NOT NULL,
  DOCUMENTO VARCHAR2(30) NOT NULL,
  CORREO VARCHAR2(150) NOT NULL,
  TELEFONO VARCHAR2(30),
  CIUDAD_ORIGEN VARCHAR2(100) NOT NULL,
  CONSTRAINT PK_CLIENTE PRIMARY KEY (ID_CLIENTE),
  CONSTRAINT UQ_CLI_DOCUMENTO UNIQUE (DOCUMENTO),
  CONSTRAINT UQ_CLI_CORREO UNIQUE (CORREO)
);

-- 8. Cabecera de reserva; una reserva puede incluir varias habitaciones
CREATE TABLE RESERVA (
  ID_RESERVA NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  ID_CLIENTE NUMBER NOT NULL,
  FECHA_RESERVA DATE DEFAULT SYSDATE NOT NULL,
  FECHA_CHECKIN DATE NOT NULL,
  FECHA_CHECKOUT DATE NOT NULL,
  ESTADO VARCHAR2(12) DEFAULT 'PENDIENTE' NOT NULL,
  FECHA_CANCELACION DATE,
  CONSTRAINT PK_RESERVA PRIMARY KEY (ID_RESERVA),
  CONSTRAINT FK_RES_CLIENTE FOREIGN KEY (ID_CLIENTE) REFERENCES CLIENTE(ID_CLIENTE),
  CONSTRAINT CK_RES_FECHAS CHECK (FECHA_CHECKOUT > FECHA_CHECKIN),
  CONSTRAINT CK_RES_ESTADO CHECK (ESTADO IN ('PENDIENTE','CONFIRMADA','CANCELADA','COMPLETADA')),
  CONSTRAINT CK_RES_DIAS CHECK (FECHA_CHECKIN = TRUNC(FECHA_CHECKIN) AND FECHA_CHECKOUT = TRUNC(FECHA_CHECKOUT)),
  CONSTRAINT CK_RES_CANCELACION CHECK ((ESTADO = 'CANCELADA' AND FECHA_CANCELACION IS NOT NULL) OR (ESTADO <> 'CANCELADA' AND FECHA_CANCELACION IS NULL))
);

-- 9. Detalle de habitaciones; admite fechas distintas por habitación
CREATE TABLE RESERVA_HABITACION (
  ID_RESERVA_HAB NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  ID_RESERVA NUMBER NOT NULL,
  ID_HABITACION NUMBER NOT NULL,
  FECHA_CHECKIN DATE NOT NULL,
  FECHA_CHECKOUT DATE NOT NULL,
  NUM_HUESPEDES NUMBER(3) NOT NULL,
  CONSTRAINT PK_RES_HAB PRIMARY KEY (ID_RESERVA_HAB),
  CONSTRAINT FK_RH_RES FOREIGN KEY (ID_RESERVA) REFERENCES RESERVA(ID_RESERVA),
  CONSTRAINT FK_RH_HAB FOREIGN KEY (ID_HABITACION) REFERENCES HABITACION(ID_HABITACION),
  CONSTRAINT UQ_RH_RES_HAB UNIQUE (ID_RESERVA, ID_HABITACION),
  CONSTRAINT CK_RH_FECHAS CHECK (FECHA_CHECKOUT > FECHA_CHECKIN),
  CONSTRAINT CK_RH_HUESPEDES CHECK (NUM_HUESPEDES > 0),
  CONSTRAINT CK_RH_DIAS CHECK (FECHA_CHECKIN = TRUNC(FECHA_CHECKIN) AND FECHA_CHECKOUT = TRUNC(FECHA_CHECKOUT))
);

-- 10. Abonos y pagos de reservas
CREATE TABLE PAGO (
  ID_PAGO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  ID_RESERVA NUMBER NOT NULL,
  FECHA_PAGO DATE DEFAULT SYSDATE NOT NULL,
  MONTO NUMBER(12,2) NOT NULL,
  MONTO_REEMBOLSADO NUMBER(12,2) DEFAULT 0 NOT NULL,
  METODO VARCHAR2(20) NOT NULL,
  ESTADO VARCHAR2(12) DEFAULT 'PENDIENTE' NOT NULL,
  CONSTRAINT PK_PAGO PRIMARY KEY (ID_PAGO),
  CONSTRAINT FK_PAG_RES FOREIGN KEY (ID_RESERVA) REFERENCES RESERVA(ID_RESERVA),
  CONSTRAINT CK_PAG_MONTO CHECK (MONTO > 0),
  CONSTRAINT CK_PAG_METODO CHECK (METODO IN ('CREDITO','DEBITO','PSE','TRANSFERENCIA','EFECTIVO')),
  CONSTRAINT CK_PAG_ESTADO CHECK (ESTADO IN ('EXITOSO','FALLIDO','PENDIENTE','REEMBOLSADO')),
  CONSTRAINT CK_PAG_REEMBOLSO CHECK (MONTO_REEMBOLSADO BETWEEN 0 AND MONTO AND
    ((ESTADO = 'REEMBOLSADO' AND MONTO_REEMBOLSADO > 0) OR
     (ESTADO <> 'REEMBOLSADO' AND MONTO_REEMBOLSADO = 0)))
);

-- 11. Servicios propios de cada alojamiento
CREATE TABLE SERVICIO (
  ID_SERVICIO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  ID_ALOJAMIENTO NUMBER NOT NULL,
  NOMBRE VARCHAR2(100) NOT NULL,
  DESCRIPCION VARCHAR2(300),
  PRECIO NUMBER(12,2) NOT NULL,
  CONSTRAINT PK_SERVICIO PRIMARY KEY (ID_SERVICIO),
  CONSTRAINT FK_SER_ALO FOREIGN KEY (ID_ALOJAMIENTO) REFERENCES ALOJAMIENTO(ID_ALOJAMIENTO),
  CONSTRAINT CK_SER_PRECIO CHECK (PRECIO >= 0)
);

-- 12. Servicios incluidos en una reserva
CREATE TABLE RESERVA_SERVICIO (
  ID_RESERVA_SERVICIO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  ID_RESERVA NUMBER NOT NULL,
  ID_SERVICIO NUMBER NOT NULL,
  CANTIDAD NUMBER(5) NOT NULL,
  PRECIO_UNITARIO NUMBER(12,2) NOT NULL,
  CONSTRAINT PK_RES_SER PRIMARY KEY (ID_RESERVA_SERVICIO),
  CONSTRAINT FK_RS_RES FOREIGN KEY (ID_RESERVA) REFERENCES RESERVA(ID_RESERVA),
  CONSTRAINT FK_RS_SER FOREIGN KEY (ID_SERVICIO) REFERENCES SERVICIO(ID_SERVICIO),
  CONSTRAINT UQ_RS_RES_SERV UNIQUE (ID_RESERVA, ID_SERVICIO),
  CONSTRAINT CK_RS_CANTIDAD CHECK (CANTIDAD > 0),
  CONSTRAINT CK_RS_PRECIO CHECK (PRECIO_UNITARIO >= 0)
);

-- 13. Resenas: 05 valida reserva completada, alojamiento visitado y fecha.
CREATE TABLE RESENA (
  ID_RESENA NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  ID_RESERVA NUMBER NOT NULL,
  ID_ALOJAMIENTO NUMBER NOT NULL,
  CALIFICACION NUMBER(1) NOT NULL,
  COMENTARIO VARCHAR2(1000),
  FECHA_RESENA DATE DEFAULT SYSDATE NOT NULL,
  CONSTRAINT PK_RESENA PRIMARY KEY (ID_RESENA),
  CONSTRAINT FK_RESE_RES FOREIGN KEY (ID_RESERVA) REFERENCES RESERVA(ID_RESERVA),
  CONSTRAINT FK_RESE_ALO FOREIGN KEY (ID_ALOJAMIENTO) REFERENCES ALOJAMIENTO(ID_ALOJAMIENTO),
  CONSTRAINT UQ_RESE_RES_ALO UNIQUE (ID_RESERVA, ID_ALOJAMIENTO),
  CONSTRAINT CK_RESE_CALIFICACION CHECK (CALIFICACION BETWEEN 1 AND 5)
);

-- 14. Usuarios internos; roles de Oracle se definirán en la entrega 3
CREATE TABLE USUARIO_SISTEMA (
  ID_USUARIO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
  ID_ALOJAMIENTO NUMBER,
  NOMBRE VARCHAR2(120) NOT NULL,
  CORREO VARCHAR2(150) NOT NULL,
  ROL_NEGOCIO VARCHAR2(25) NOT NULL,
  ACTIVO CHAR(1) DEFAULT 'S' NOT NULL,
  CONSTRAINT PK_USUARIO_SISTEMA PRIMARY KEY (ID_USUARIO),
  CONSTRAINT FK_US_ALO FOREIGN KEY (ID_ALOJAMIENTO) REFERENCES ALOJAMIENTO(ID_ALOJAMIENTO),
  CONSTRAINT UQ_US_CORREO UNIQUE (CORREO),
  CONSTRAINT CK_US_ROL CHECK (ROL_NEGOCIO IN ('RECEPCION','ADMIN_ALOJAMIENTO','GERENTE','AUDITOR')),
  CONSTRAINT CK_US_ACTIVO CHECK (ACTIVO IN ('S','N')),
  CONSTRAINT CK_US_ASIGNACION CHECK (
    (ROL_NEGOCIO IN ('RECEPCION','ADMIN_ALOJAMIENTO') AND ID_ALOJAMIENTO IS NOT NULL) OR
    (ROL_NEGOCIO IN ('GERENTE','AUDITOR') AND ID_ALOJAMIENTO IS NULL))
);

