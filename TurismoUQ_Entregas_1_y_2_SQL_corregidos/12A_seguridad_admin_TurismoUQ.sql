-- Para SQL: ejecutar una sentencia. Para PL/SQL: seleccionar el bloque completo
-- DECLARE/BEGIN o CREATE...END; sin la linea / y usar Ejecutar sentencia SQL.
-- Conservar la misma conexion para SAVEPOINT/ROLLBACK. Activar salida DBMS Output.
-- CONEXION DBEAVER: SYS. Ejecutar solo en esta cuenta.
DECLARE
BEGIN
 IF SYS_CONTEXT('USERENV','SESSION_USER')<>'SYS' THEN
  RAISE_APPLICATION_ERROR(-20410,'Seleccionar la conexion SYS en DBeaver');
 END IF;
END;
/
-- SYS AS SYSDBA EN LA PDB (no CDB$ROOT). Una instalacion; no volver a crear usuarios existentes.
DECLARE v_n NUMBER;
BEGIN
 IF SYS_CONTEXT('USERENV','CON_NAME')='CDB$ROOT' THEN
  RAISE_APPLICATION_ERROR(-20401,'Conectar SYS AS SYSDBA al servicio de la PDB');
 END IF;
 SELECT COUNT(*) INTO v_n FROM DBA_USERS WHERE USERNAME='TURISMOUQ';
 IF v_n=0 THEN RAISE_APPLICATION_ERROR(-20401,'Crear primero el propietario TURISMOUQ en esta PDB'); END IF;
 SELECT COUNT(*) INTO v_n FROM DBA_TAB_COLUMNS WHERE OWNER='TURISMOUQ' AND
  ((TABLE_NAME='PAGO' AND COLUMN_NAME='MONTO_REEMBOLSADO') OR
   (TABLE_NAME='RESERVA' AND COLUMN_NAME='FECHA_CANCELACION'));
 IF v_n<>2 THEN RAISE_APPLICATION_ERROR(-20402,'Instalar primero las entregas 1 y 2 corregidas'); END IF;
END;
/
CREATE ROLE RL_TQ_RECEPCION;
CREATE ROLE RL_TQ_ADMIN_ALOJ;
CREATE ROLE RL_TQ_GERENTE;
CREATE ROLE RL_TQ_AUDITOR;
CREATE PROFILE PF_TQ_OPERACION LIMIT SESSIONS_PER_USER 2 IDLE_TIME 15 CONNECT_TIME 60
 FAILED_LOGIN_ATTEMPTS 5 PASSWORD_LIFE_TIME 180;
ALTER SYSTEM SET RESOURCE_LIMIT=TRUE;
-- Ejecutar este DECLARE completo. DBeaver pide cuatro parametros de tipo String.
-- Escribir las claves sin comillas adicionales y no guardarlas dentro del SQL.
DECLARE
 v_recepcion VARCHAR2(128):=:clave_recepcion;
 v_admin VARCHAR2(128):=:clave_admin;
 v_gerente VARCHAR2(128):=:clave_gerente;
 v_auditor VARCHAR2(128):=:clave_auditor;
 PROCEDURE crear(p_usuario VARCHAR2,p_clave VARCHAR2) IS
 BEGIN
  IF p_clave IS NULL OR LENGTHB(p_clave)>30 OR INSTR(p_clave,CHR(34))>0
     OR INSTR(p_clave,CHR(10))>0 OR INSTR(p_clave,CHR(13))>0 THEN
   RAISE_APPLICATION_ERROR(-20411,'Clave de 1 a 30 bytes, sin comillas dobles ni saltos de linea');
  END IF;
  EXECUTE IMMEDIATE 'CREATE USER '||p_usuario||' IDENTIFIED BY "'||p_clave||'" PROFILE PF_TQ_OPERACION';
 END;
BEGIN
 crear('TQ_E3_RECEPCION',v_recepcion);
 crear('TQ_E3_ADMIN_ALOJ',v_admin);
 crear('TQ_E3_GERENTE',v_gerente);
 crear('TQ_E3_AUDITOR',v_auditor);
END;
/
GRANT CREATE SESSION TO TQ_E3_RECEPCION,TQ_E3_ADMIN_ALOJ,TQ_E3_GERENTE,TQ_E3_AUDITOR;
GRANT RL_TQ_RECEPCION TO TQ_E3_RECEPCION;
GRANT RL_TQ_ADMIN_ALOJ TO TQ_E3_ADMIN_ALOJ;
GRANT RL_TQ_GERENTE TO TQ_E3_GERENTE;
GRANT RL_TQ_AUDITOR TO TQ_E3_AUDITOR;
