-- 2.2B, C, D / Figura 2.3: exigir exactamente los codigos previstos.
DECLARE
  v_reserva NUMBER; v_hab NUMBER; v_in DATE; v_out DATE; v_ok BOOLEAN;
BEGIN
  SAVEPOINT prueba_errores;
  v_ok:=FALSE;
  BEGIN
    PKG_TURISMOUQ.SP_CREAR_RESERVA(1,1,DATE '2026-12-12',DATE '2026-12-10',1,v_reserva);
  EXCEPTION WHEN OTHERS THEN
    IF SQLCODE<>-20010 THEN RAISE; END IF; v_ok:=TRUE;
    DBMS_OUTPUT.PUT_LINE('CORRECTO: '||SQLERRM);
  END;
  IF NOT v_ok THEN RAISE_APPLICATION_ERROR(-20990,'Fallo: fechas invalidas aceptadas'); END IF;
  v_ok:=FALSE;
  BEGIN
    PKG_TURISMOUQ.SP_CREAR_RESERVA(1,1,DATE '2026-12-10',DATE '2026-12-12',999,v_reserva);
  EXCEPTION WHEN OTHERS THEN
    IF SQLCODE<>-20015 THEN RAISE; END IF; v_ok:=TRUE;
    DBMS_OUTPUT.PUT_LINE('CORRECTO: '||SQLERRM);
  END;
  IF NOT v_ok THEN RAISE_APPLICATION_ERROR(-20990,'Fallo: capacidad invalida aceptada'); END IF;
  SELECT rh.ID_HABITACION,rh.FECHA_CHECKIN,rh.FECHA_CHECKOUT INTO v_hab,v_in,v_out
  FROM RESERVA_HABITACION rh JOIN RESERVA r ON r.ID_RESERVA=rh.ID_RESERVA
  WHERE r.ESTADO='CONFIRMADA' ORDER BY rh.ID_RESERVA_HAB FETCH FIRST 1 ROW ONLY;
  v_ok:=FALSE;
  BEGIN PKG_TURISMOUQ.SP_CREAR_RESERVA(1,v_hab,v_in,v_out,1,v_reserva);
  EXCEPTION WHEN OTHERS THEN
    IF SQLCODE<>-20016 THEN RAISE; END IF; v_ok:=TRUE;
    DBMS_OUTPUT.PUT_LINE('CORRECTO: '||SQLERRM);
  END;
  IF NOT v_ok THEN RAISE_APPLICATION_ERROR(-20990,'Fallo: duplicado aceptado'); END IF;
  ROLLBACK TO prueba_errores;
EXCEPTION WHEN OTHERS THEN ROLLBACK TO prueba_errores; RAISE;
END;
