  (SELECT SUM(t.PRECIO_NOCHE*(LEAST(DATE '2026-01-17',s.FECHA_FIN+1)-
    GREATEST(DATE '2026-01-15',s.FECHA_INICIO)))
   FROM TARIFA t JOIN TEMPORADA s ON s.ID_TEMPORADA=t.ID_TEMPORADA
