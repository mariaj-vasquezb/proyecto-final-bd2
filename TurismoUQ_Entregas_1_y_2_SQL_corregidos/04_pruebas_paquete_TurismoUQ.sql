-- 2.2A / Figura 2.2: escoger habitacion realmente libre, sin depender del ID 1.
DECLARE
  v_hab NUMBER; v_reserva NUMBER; v_n NUMBER;
BEGIN
  SAVEPOINT prueba_paquete;
  SELECT h.ID_HABITACION INTO v_hab FROM HABITACION h
  WHERE h.ACTIVA='S' AND NOT EXISTS (
    SELECT 1 FROM RESERVA_HABITACION d JOIN RESERVA r ON r.ID_RESERVA=d.ID_RESERVA
    WHERE d.ID_HABITACION=h.ID_HABITACION AND r.ESTADO IN ('CONFIRMADA','COMPLETADA')
      AND d.FECHA_CHECKIN<DATE '2026-12-12' AND d.FECHA_CHECKOUT>DATE '2026-12-10')
  ORDER BY h.ID_HABITACION FETCH FIRST 1 ROW ONLY;
  PKG_TURISMOUQ.SP_CREAR_RESERVA(1,v_hab,DATE '2026-12-10',DATE '2026-12-12',1,v_reserva);
  SELECT COUNT(*) INTO v_n FROM RESERVA_HABITACION WHERE ID_RESERVA=v_reserva;
  IF v_n<>1 THEN RAISE_APPLICATION_ERROR(-20990,'Fallo: cabecera sin detalle'); END IF;
  DBMS_OUTPUT.PUT_LINE('Reserva creada para prueba: '||v_reserva||'; habitacion: '||v_hab);
  ROLLBACK TO prueba_paquete;
EXCEPTION WHEN OTHERS THEN ROLLBACK TO prueba_paquete; RAISE;
END;
