CREATE TABLE HISTORICO_RESERVA (
    ID_HISTORICO NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ID_RESERVA_ORIGEN NUMBER NOT NULL,
    ID_CLIENTE NUMBER NOT NULL,
    FECHA_RESERVA DATE,
    FECHA_CHECKIN DATE NOT NULL,
    FECHA_CHECKOUT DATE NOT NULL,
    ESTADO VARCHAR2(12) NOT NULL,
    FECHA_ARCHIVO TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_HIST_RESERVA PRIMARY KEY (ID_HISTORICO),
    CONSTRAINT UQ_HIST_RESERVA_ORIGEN UNIQUE (ID_RESERVA_ORIGEN)
) TABLESPACE TS_TURISMOUQ_HIST;

-- Vista de metadatos disponible para TURISMOUQ: verifica el tablespace real.
-- FIGURA 2.11 - Verificacion de ubicacion de HISTORICO_RESERVA
SELECT TABLE_NAME, TABLESPACE_NAME
FROM USER_TABLES
WHERE TABLE_NAME = 'HISTORICO_RESERVA';

-- Comprobar que esta preparado y que no se han trasladado datos por error.
SELECT COUNT(*) AS RESERVAS_EN_HISTORICO
FROM HISTORICO_RESERVA;

